export type Translations = typeof TR;

/** Безопасный хелпер для получения строкового перевода */
export function t(lang: string, key: string): string {
  const dict = TR[lang as keyof typeof TR] ?? TR.ru;
  const val = (dict as unknown as Record<string, unknown>)[key];
  return typeof val === "string" ? val : key;
}

/** Получить массив stages для нужного языка */
export function getStages(lang: string): string[] {
  const dict = TR[lang as keyof typeof TR] ?? TR.ru;
  return [...dict.stages] as string[];
}
